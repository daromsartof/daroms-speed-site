/** The `app/theme.css` file for a DNA: Tailwind v4 @theme tokens plus texture utilities. */
export function renderThemeCss(dna: Dna): string {
  const colors = colorTokens(dna)
  const pair = fontPair(dna.fonts)
  const sameFamily = pair.display.family === pair.body.family
  const scale = TYPE_SCALES[dna.scale]
  const [card, control, media] = RADIUS[dna.radius]
  const [duration, ease] = MOTION[dna.motion]
  const ruleWidth = dna.rules === 'none' ? '0px' : dna.rules === 'hairline' ? '1px' : '3px'
  const lines: string[] = [`/* ${GENERATED} */`, `/* ${designRead(dna)} */`, '@theme {']
  for (const token of COLOR_TOKENS) lines.push(`  --color-${token}: ${oklchCss(colors[token])};`)
  lines.push('')
  lines.push(`  --font-display: var(--font-face-display), ${fallback(pair.display.family)};`)
  lines.push(
    `  --font-body: var(${sameFamily ? '--font-face-display' : '--font-face-body'}), ${fallback(pair.body.family)};`,
  )
  lines.push(`  --font-mono: ${pair.mono ? 'var(--font-face-mono), ' : ''}${fallback('Mono')};`)
  lines.push('')
  for (const [name, [size, leading, tracking]] of Object.entries(scale)) {
    lines.push(`  --text-${name}: ${size};`)
    lines.push(`  --text-${name}--line-height: ${leading};`)
    lines.push(`  --text-${name}--letter-spacing: ${tracking};`)
  }
  lines.push('')
  lines.push(
    `  --radius-card: ${card};`,
    `  --radius-control: ${control};`,
    `  --radius-media: ${media};`,
  )
  lines.push(
    `  --spacing-section: ${SECTION_SPACE[dna.density]};`,
    '  --spacing-gutter: clamp(1.25rem, 4vw, 3rem);',
  )
  lines.push(
    `  --container-content: ${dna.grid === 'fullbleed' ? '96rem' : '80rem'};`,
    '  --container-prose: 42rem;',
  )
  lines.push(`  --ease-brand: ${ease};`, `  --duration-brand: ${duration};`)
  lines.push('}', '')
  lines.push(
    `:root {`,
    `  --rule-width: ${ruleWidth};`,
    `  color-scheme: ${dna.palette.mode};`,
    '}',
    '',
  )
  lines.push('@utility rule-t { border-top: var(--rule-width) solid var(--color-rule); }')
  lines.push('@utility rule-b { border-bottom: var(--rule-width) solid var(--color-rule); }')
  lines.push(
    `@utility texture-grain { background-image: ${grainUrl}; background-blend-mode: multiply; }`,
  )
  lines.push(
    '@utility texture-halftone { background-image: radial-gradient(var(--color-line) 1px, transparent 1.2px); background-size: 7px 7px; }',
  )
  lines.push(
    '@utility texture-grid { background-image: linear-gradient(var(--color-line) 1px, transparent 1px), linear-gradient(90deg, var(--color-line) 1px, transparent 1px); background-size: 4rem 4rem; }',
  )
  lines.push(
    '@utility texture-mesh { background-image: radial-gradient(60% 50% at 15% 20%, color-mix(in oklch, var(--color-accent) 22%, transparent), transparent), radial-gradient(50% 40% at 85% 70%, color-mix(in oklch, var(--color-secondary) 18%, transparent), transparent); }',
  )
  if (dna.texture === 'grain' || dna.texture === 'paper') {
    const opacity = dna.texture === 'paper' ? 0.06 : 0.09
    lines.push('')
    lines.push(
      `body::before { content: ''; position: fixed; inset: 0; z-index: 60; pointer-events: none; opacity: ${opacity}; background-image: ${grainUrl}; }`,
    )
  }
  return `${lines.join('\n')}\n`
}

function fontCall(spec: FontSpec, variable: string, preload: boolean): string {
  const opts = [`subsets: ['latin']`, `variable: '${variable}'`, `display: 'swap'`]
  if (spec.weights) opts.push(`weight: [${spec.weights.map((w) => `'${w}'`).join(', ')}]`)
  if (spec.italic) opts.push(`style: ['normal', 'italic']`)
  if (spec.axes?.length) opts.push(`axes: [${spec.axes.map((a) => `'${a}'`).join(', ')}]`)
  if (!preload) opts.push('preload: false')
  return `${fontImportName(spec.family)}({ ${opts.join(', ')} })`
}

/** The `app/fonts.ts` file: next/font loaders for the DNA's pairing. */
export function renderFontsTs(dna: Dna): string {
  const pair = fontPair(dna.fonts)
  const sameFamily = pair.display.family === pair.body.family
  const families = new Set([
    pair.display.family,
    pair.body.family,
    ...(pair.mono ? [pair.mono.family] : []),
  ])
  const imports = [...families].map(fontImportName).sort().join(', ')
  const out = [`// ${GENERATED}`, `import { ${imports} } from 'next/font/google'`, '']
  const vars = ['displayFont']
  out.push(`export const displayFont = ${fontCall(pair.display, '--font-face-display', true)}`)
  if (!sameFamily) {
    out.push(`export const bodyFont = ${fontCall(pair.body, '--font-face-body', true)}`)
    vars.push('bodyFont')
  }
  if (pair.mono && pair.mono.family !== pair.display.family) {
    out.push(`export const monoFont = ${fontCall(pair.mono, '--font-face-mono', false)}`)
    vars.push('monoFont')
  }
  out.push(
    '',
    `export const fontVariables = [${vars.map((v) => `${v}.variable`).join(', ')}].join(' ')`,
  )
  return `${out.join('\n')}\n`
}

/** The `app/theme.ts` file: literal colors that browser chrome needs. */
export function renderThemeTs(dna: Dna): string {
  const colors = colorTokens(dna)
  return [
    `/* eslint-disable no-restricted-syntax -- ${GENERATED} Browser chrome needs literal colors. */`,
    `export const themeColor = '${oklchToHex(colors.surface)}'`,
    `export const colorScheme = '${dna.palette.mode}' as const`,
    `export const dnaAttributes = ${JSON.stringify({
      'data-archetype': dna.archetype,
      'data-motion': dna.motion,
      'data-three': dna.three,
      'data-texture': dna.texture,
      'data-radius': dna.radius,
    })} as const`,
    '',
  ].join('\n')
}

const HUE_NAMES: readonly [number, string][] = [
  [15, 'red'],
  [45, 'orange'],
  [75, 'amber'],
  [105, 'olive'],
  [145, 'green'],
  [175, 'teal'],
  [205, 'cyan'],
  [245, 'blue'],
  [275, 'indigo'],
  [305, 'violet'],
  [340, 'magenta'],
  [360, 'rose'],
]
export function hueName(hue: number): string {
  return HUE_NAMES.find(([max]) => hue <= max)?.[1] ?? 'red'
}

/** One-line "Design Read" summarising a DNA, for site.spec.md and theme.css. */
export function designRead(dna: Dna): string {
  const a = ARCHETYPES[dna.archetype]
  const pair = fontPair(dna.fonts)
  return [
    `Reading this as: ${dna.industry} site, ${a.label} language (${a.read})`,
    `type ${pair.display.family} / ${pair.body.family}`,
    `${dna.palette.mode} palette, ${hueName(dna.palette.hue)} accent`,
    `${dna.grid} grid, ${dna.radius} corners, ${dna.texture} texture, ${dna.density} density`,
    `${dna.motion} motion, 3D ${dna.three}, imagery ${dna.imagery}`,
  ].join('; ')
}

/** `app/icon.svg`: monogram on the accent, corner radius from the DNA. Replace with a real logo when there is one. */
export function renderIconSvg(dna: Dna, siteName: string): string {
  const colors = colorTokens(dna)
  const letter = (siteName.match(/[\p{L}\p{N}]/u)?.[0] ?? 'S').toUpperCase()
  const radius = { none: 0, subtle: 6, soft: 14, pill: 32 }[dna.radius]
  const serif = SERIF.test(fontPair(dna.fonts).display.family)
  const family = serif ? 'Georgia, serif' : 'Helvetica, Arial, sans-serif'
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><!-- dss-monogram -->',
    `<rect width="64" height="64" rx="${radius}" fill="${oklchToHex(colors.accent)}"/>`,
    `<text x="32" y="44" text-anchor="middle" font-family="${family}" font-size="38" font-weight="600" fill="${oklchToHex(colors['accent-ink'])}">${letter}</text>`,
    '</svg>',
    '',
  ].join('')
}
