import { join } from 'node:path'
import { writeFile } from './fsx.ts'
import type { Hook, ModuleSpec } from './modules.ts'

/** Regenerates lib/modules.ts and components/site/module-slots.tsx from the installed modules. */
export function writeModuleSlots(root: string, specs: readonly ModuleSpec[]) {
  const pick = (kind: 'sitemap' | 'llms' | 'bodyEnd') =>
    specs.flatMap((s) => (s.hooks?.[kind] ? [s.hooks[kind] as Hook] : []))
  const sitemap = pick('sitemap')
  const llms = pick('llms')
  const bodyEnd = pick('bodyEnd')
  const imports = (hooks: Hook[]) => hooks.map((h) => `import { ${h.import} } from '${h.from}'`)
  writeFile(
    join(root, 'lib/modules.ts'),
    [
      '// GENERATED by `dss module`: data hooks of installed modules. Do not edit by hand.',
      "import type { LlmsEntry, SitemapEntry } from '@dss/seo'",
      ...imports([...sitemap, ...llms]),
      '',
      '/** Extra sitemap entries contributed by modules (blog posts...). */',
      'export async function moduleSitemap(): Promise<SitemapEntry[]> {',
      sitemap.length
        ? `  return (await Promise.all([${sitemap.map((h) => `${h.import}()`).join(', ')}])).flat()`
        : '  return []',
      '}',
      '',
      '/** Extra llms.txt sections contributed by modules. */',
      'export async function moduleLlms(): Promise<Record<string, LlmsEntry[]>> {',
      llms.length
        ? `  return Object.assign({}, ...(await Promise.all([${llms.map((h) => `${h.import}()`).join(', ')}])))`
        : '  return {}',
      '}',
      '',
    ].join('\n'),
  )
  writeFile(
    join(root, 'components/site/module-slots.tsx'),
    [
      '// GENERATED by `dss module`: UI slots of installed modules. Do not edit by hand.',
      ...imports(bodyEnd),
      '',
      '/** Rendered at the end of <body> (analytics scripts, consent...). */',
      'export function ModuleBodyEnd() {',
      bodyEnd.length
        ? `  return (\n    <>\n${bodyEnd.map((h) => `      <${h.import} />`).join('\n')}\n    </>\n  )`
        : '  return null',
      '}',
      '',
    ].join('\n'),
  )
}
