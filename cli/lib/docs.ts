import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { COMMANDS } from '../commands.ts'

const GENERATED = '<!-- GENERATED by `dss docs`: do not edit by hand. -->'
const BASE = 'https://github.com/daromsartof/daroms-speed-site/blob/main/docs'

/** Hand-written pages in reading order (index first), excluding generated ones. */
export function docPages(docs: string): string[] {
  const order = [
    'index.md',
    'getting-started.md',
    'architecture.md',
    'design-dna.md',
    'ai-layer.md',
    'modules.md',
    'deploy.md',
    'aimkit.md',
    'factory.md',
  ]
  const present = readdirSync(docs).filter((f) => f.endsWith('.md') && f !== 'cli.md')
  return [
    ...order.filter((f) => present.includes(f)),
    ...present.filter((f) => !order.includes(f)).sort(),
  ]
}

export function pageSummary(text: string): { title: string; summary: string } {
  return {
    title: /^# (.+)$/m.exec(text)?.[1]?.trim() ?? '',
    summary: /^> (.+)$/m.exec(text)?.[1]?.trim() ?? '',
  }
}

/** docs/cli.md from the command table. */
export function buildCliDoc(): string {
  const rows = Object.entries(COMMANDS).map(
    ([name, c]) => `| \`dss ${name}\` | ${c.describe.replace(/\|/g, '\\|')} |`,
  )
  return [
    GENERATED,
    '# CLI reference',
    '',
    '> Every dss command, generated from the CLI itself. In a site run them as `pnpm dss <command>`.',
    '',
    '| Command | Usage |',
    '|---|---|',
    ...rows,
    '',
  ].join('\n')
}

/** docs/llms.txt (llmstxt.org): one line per page for answer engines and agents. */
export function buildLlms(docs: string): string {
  const pages = [...docPages(docs), 'cli.md'].filter(
    (f) => f === 'cli.md' || existsSync(join(docs, f)),
  )
  const entries = pages.map((f) => {
    const text = f === 'cli.md' ? buildCliDoc() : readFileSync(join(docs, f), 'utf8')
    const { title, summary } = pageSummary(text)
    return `- [${title}](${BASE}/${f}): ${summary}`
  })
  const { summary } = pageSummary(readFileSync(join(docs, 'index.md'), 'utf8'))
  return [
    '# daroms-speed-site',
    '',
    `> ${summary}`,
    '',
    '## Docs',
    '',
    ...entries,
    '',
    '## Catalog',
    '',
    `- [CATALOG.md](${BASE.replace('/docs', '')}/CATALOG.md): tokens, components, sections, modules, archetypes, font pairs, package APIs`,
    '',
  ].join('\n')
}

/** docs/llms-full.txt: every page and the catalog in one file. */
export function buildLlmsFull(docs: string, core: string): string {
  const pages = docPages(docs).map((f) => readFileSync(join(docs, f), 'utf8').trim())
  return [
    ...pages,
    buildCliDoc().replace(`${GENERATED}\n`, '').trim(),
    readFileSync(join(core, 'CATALOG.md'), 'utf8')
      .replace(/^<!--.*-->\n/, '')
      .trim(),
    '',
  ].join('\n\n---\n\n')
}

/** Relative Markdown links that point to a missing docs page. */
export function brokenLinks(docs: string): string[] {
  const broken: string[] = []
  for (const f of docPages(docs)) {
    for (const m of readFileSync(join(docs, f), 'utf8').matchAll(/\]\(([\w-]+\.md)(#[\w-]+)?\)/g)) {
      const target = m[1] as string
      if (target !== 'cli.md' && !existsSync(join(docs, target))) broken.push(`${f} -> ${target}`)
    }
  }
  return broken
}
