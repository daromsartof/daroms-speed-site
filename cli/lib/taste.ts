// Taste metrics on the rendered page: count instead of judge. A number cannot be argued with;
// "make it look better" only invites a new set of defaults.
import { rgbToOklch, type Rgb } from '../../packages/design/src/color.ts'

/** Raw readings taken inside the page (see collectMeasures). Colors are normalised to rgb(). */
export type RawMeasures = {
  colors: { css: string; count: number; sample: string }[]
  radii: { px: number; sample: string }[]
  fontSizes: { px: number; sample: string }[]
  fontFamilies: string[]
  gradients: string[]
  emoji: string[]
  actions: Action[]
}

/** A clickable element; x/y are page coordinates, `main` is true inside <main>. */
export type Action = {
  label: string
  href: string
  x: number
  y: number
  w: number
  h: number
  inline: boolean
  main: boolean
}

/** What the DNA allows, read from the generated app/theme.css. */
export type ThemeRef = { hues: number[]; radii: number[]; sizes: number; families: number }

export type Metric = { key: string; label: string; value: number; max: number; detail: string[] }

/** Below this OKLCH chroma a color is a neutral (tinted surfaces and inks included). */
const VIVID_CHROMA = 0.06
const HUE_TOLERANCE = 20
/** WCAG 2.5.8 minimum target; the comfortable 44 px stays with the dss-designer agent. */
export const MIN_TARGET = 24
/** Utility sizes primitives may use next to the DNA scale (body, small, caption). */
const EXTRA_SIZES = 3

const toPx = (value: string): number | undefined => {
  const m = /^([\d.]+)(rem|px)?$/.exec(value.trim())
  if (!m) return undefined
  return Number(m[1]) * (m[2] === 'rem' ? 16 : 1)
}

/** Reads token hues, radii and the type scale from app/theme.css (generated by `dss theme`). */
export function themeRef(css: string): ThemeRef {
  const hues: number[] = []
  for (const m of css.matchAll(/--color-[\w-]+:\s*oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)\)/g)) {
    if (Number(m[2]) >= VIVID_CHROMA) hues.push(Number(m[3]))
  }
  const radii: number[] = []
  for (const m of css.matchAll(/--radius-[\w-]+:\s*([^;]+);/g)) {
    const px = toPx(m[1]!)
    if (px !== undefined && px > 0 && px < 999) radii.push(px)
  }
  // --text-x--line-height and --text-x--letter-spacing belong to --text-x
  const sizes = [...css.matchAll(/--text-([\w-]+):\s/g)].filter((m) => !m[1]!.includes('--')).length
  // display, body and mono tokens: a face variable each, or a system stack (mono without a face)
  const families = new Set(
    [...css.matchAll(/--font-(?:display|body|mono):\s*([^;]+);/g)].map(
      (m) => /var\((--font-face-\w+)\)/.exec(m[1]!)?.[1] ?? m[1]!.split(',')[0]!.trim(),
    ),
  )
  return { hues, radii, sizes: sizes + EXTRA_SIZES, families: Math.max(1, families.size) }
}

export function parseRgb(css: string): { rgb: Rgb; alpha: number } | null {
  const m = /^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:[,\s/]+([\d.]+))?\s*\)$/.exec(
    css.trim(),
  )
  if (!m) return null
  const rgb: Rgb = [Number(m[1]) / 255, Number(m[2]) / 255, Number(m[3]) / 255]
  return { rgb, alpha: m[4] === undefined ? 1 : Number(m[4]) }
}

const hueDistance = (a: number, b: number) => {
  const d = Math.abs(a - b) % 360
  return d > 180 ? 360 - d : d
}

const HUE_NAMES: [number, string][] = [
  [20, 'red'],
  [50, 'orange'],
  [100, 'yellow'],
  [150, 'green'],
  [200, 'cyan'],
  [250, 'blue'],
  [300, 'violet'],
  [345, 'pink'],
  [360, 'red'],
]
const hueName = (h: number) => HUE_NAMES.find(([max]) => h < max)![1]

/** Vivid colors on the page whose hue matches no DNA color token, grouped in 20-degree families. */
export function offPalette(colors: RawMeasures['colors'], hues: number[]) {
  const off = new Map<number, { count: number; sample: string }>()
  for (const color of colors) {
    const parsed = parseRgb(color.css)
    if (!parsed || parsed.alpha < 0.5) continue
    const { c, h } = rgbToOklch(parsed.rgb)
    if (c < VIVID_CHROMA || hues.some((ref) => hueDistance(h, ref) <= HUE_TOLERANCE)) continue
    const bucket = (Math.round(h / HUE_TOLERANCE) * HUE_TOLERANCE) % 360
    const entry = off.get(bucket) ?? { count: 0, sample: color.sample }
    entry.count += color.count
    off.set(bucket, entry)
  }
  return [...off.entries()].map(([h, e]) => ({ name: `${hueName(h)} ${h}deg`, ...e }))
}

/** Distinct values within half a pixel (browser rounding). */
function distinct<T extends { px: number }>(items: T[]): T[] {
  const seen = new Map<number, T>()
  for (const item of items) {
    const key = Math.round(item.px * 2) / 2
    if (!seen.has(key)) seen.set(key, item)
  }
  return [...seen.values()].sort((a, b) => a.px - b.px)
}

function groupBy<T>(items: T[], key: (item: T) => string, value: (item: T) => string) {
  const groups = new Map<string, Set<string>>()
  for (const item of items) {
    const set = groups.get(key(item)) ?? new Set<string>()
    set.add(value(item))
    groups.set(key(item), set)
  }
  return [...groups.entries()].filter(([, values]) => values.size > 1)
}

const contains = (outer: Action, inner: Action) =>
  outer.x <= inner.x &&
  outer.y <= inner.y &&
  outer.x + outer.w >= inner.x + inner.w &&
  outer.y + outer.h >= inner.y + inner.h

/**
 * WCAG 2.5.8: a target under 24 px still passes when a 24 px circle on its centre touches no other
 * target and no other undersized target's circle. Inline text links are exempt.
 */
export function undersized(actions: Action[]): Action[] {
  const radius = MIN_TARGET / 2
  const small = actions.filter((a) => !a.inline && Math.min(a.w, a.h) < MIN_TARGET)
  const centre = (a: Action) => [a.x + a.w / 2, a.y + a.h / 2] as const
  const toRect = ([px, py]: readonly [number, number], b: Action) =>
    Math.hypot(Math.max(b.x - px, 0, px - b.x - b.w), Math.max(b.y - py, 0, py - b.y - b.h))
  return small.filter((a) =>
    actions.some((b) => {
      if (b === a || contains(a, b) || contains(b, a)) return false
      if (toRect(centre(a), b) < radius) return true
      const [bx, by] = centre(b)
      return small.includes(b) && Math.hypot(centre(a)[0] - bx, centre(a)[1] - by) < MIN_TARGET
    }),
  )
}

/** Turns readings into metrics; a metric fails when value > max. */
export function scoreMeasures(raw: RawMeasures, theme?: ThemeRef): Metric[] {
  const metrics: Metric[] = []
  if (theme) {
    const off = offPalette(raw.colors, theme.hues)
    metrics.push({
      key: 'offPalette',
      label: 'off-palette hues',
      value: off.length,
      max: 0,
      detail: off.map((f) => `${f.name} (${f.count}): ${f.sample}`),
    })
    const allowed = [0, ...theme.radii]
    const radii = distinct(raw.radii).filter((r) => !allowed.some((a) => Math.abs(a - r.px) <= 1))
    metrics.push({
      key: 'radii',
      label: 'radii off the DNA scale',
      value: radii.length,
      max: 0,
      detail: radii.map((r) => `${r.px}px: ${r.sample}`),
    })
  }
  const sizes = distinct(raw.fontSizes)
  metrics.push({
    key: 'sizes',
    label: 'type sizes',
    value: sizes.length,
    max: theme?.sizes ?? 9,
    detail: sizes.map((s) => `${s.px}px`),
  })
  metrics.push({
    key: 'families',
    label: 'font families',
    value: raw.fontFamilies.length,
    max: theme?.families ?? 3,
    detail: raw.fontFamilies,
  })
  metrics.push({
    key: 'gradients',
    label: 'colourful gradients',
    value: raw.gradients.length,
    max: 0,
    detail: raw.gradients,
  })
  metrics.push({ key: 'emoji', label: 'emoji', value: raw.emoji.length, max: 0, detail: raw.emoji })
  // links in the content only: logo + Home, or nav Contact + a CTA, are conventions
  const links = raw.actions.filter((a) => a.main && a.label && a.href)
  const labelsPerTarget = groupBy(
    links,
    (a) => a.href,
    (a) => a.label.toLowerCase(),
  )
  metrics.push({
    key: 'labelsPerTarget',
    label: 'one destination, several labels',
    value: labelsPerTarget.length,
    max: 0,
    detail: labelsPerTarget.map(([href, labels]) => `${href}: ${[...labels].join(' / ')}`),
  })
  const targetsPerLabel = groupBy(
    links,
    (a) => a.label.toLowerCase(),
    (a) => a.href,
  )
  metrics.push({
    key: 'targetsPerLabel',
    label: 'one label, several destinations',
    value: targetsPerLabel.length,
    max: 0,
    detail: targetsPerLabel.map(([label, hrefs]) => `"${label}": ${[...hrefs].join(' / ')}`),
  })
  const unnamed = raw.actions.filter((a) => !a.label)
  metrics.push({
    key: 'unnamed',
    label: 'actions without a name',
    value: unnamed.length,
    max: 0,
    detail: unnamed.map((a) => `${a.href || 'button'} ${a.w}x${a.h}`),
  })
  const small = undersized(raw.actions)
  metrics.push({
    key: 'targets',
    label: `targets < ${MIN_TARGET}px`,
    value: small.length,
    max: 0,
    detail: small.map((a) => `${a.label || a.href || '(no name)'} ${a.w}x${a.h}`),
  })
  return metrics
}

export const failing = (metrics: Metric[]) => metrics.filter((m) => m.value > m.max)
