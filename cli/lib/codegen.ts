import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { camel, pascal, writeFile } from './fsx.ts'
import { toTs } from './serialize.ts'

/** app/page.tsx for "/", app/<route>/page.tsx otherwise. */
export function pageFile(route: string): string {
  return route === '/' ? 'app/page.tsx' : `app${route}/page.tsx`
}

export const contentFile = (name: string) => `content/${name}.ts`
export const contentVar = (name: string) => camel(name)

/** Content literal: internal hrefs are typed routes (`as Route`) so typedRoutes accepts them. */
function contentTs(value: unknown, indent = 1): string {
  const text = toTs(value, indent)
  return text.replace(/(\bhref: )('\/[^']*')/g, '$1$2 as Route')
}

export type ContentBlock = { key: string; value: unknown }

export function renderContent(
  name: string,
  meta: { title: string; description: string },
  blocks: readonly ContentBlock[],
) {
  const body = [
    `  meta: ${contentTs(meta)},`,
    ...blocks.map((b) => `  ${b.key}: ${contentTs(b.value)},`),
  ]
  const needsRoute = body.some((line) => line.includes(' as Route'))
  return [
    ...(needsRoute ? ["import type { Route } from 'next'", ''] : []),
    `// Copy for ${name}. Edit text here; sections receive it as props. [Brackets] are placeholders.`,
    `export const ${contentVar(name)} = {`,
    ...body,
    '} as const',
    '',
  ].join('\n')
}

export type PageSection = { component: string; importPath: string; key: string }

export function renderPage(route: string, name: string, sections: readonly PageSection[]) {
  const imports = [...new Map(sections.map((s) => [s.importPath, s.component])).entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([path, component]) => `import { ${component} } from '${path}'`)
  const v = contentVar(name)
  return [
    "import type { Metadata } from 'next'",
    "import { pageMetadata } from '@dss/seo'",
    ...imports,
    `import { ${v} } from '@/content/${name}'`,
    "import manifest from '@/site.manifest'",
    '',
    `export const metadata: Metadata = pageMetadata(manifest, { ...${v}.meta, path: '${route}' })`,
    '',
    `export default function ${pascal(name)}Page() {`,
    '  return (',
    '    <main id="main">',
    ...sections.map((s) => `      <${s.component} {...${v}.${s.key}} />`),
    '    </main>',
    '  )',
    '}',
    '',
  ].join('\n')
}

/** Unique content keys when a section repeats on a page: hero, faq, faq2. */
export function sectionKeys(ids: readonly string[]): string[] {
  const seen = new Map<string, number>()
  return ids.map((id) => {
    const n = (seen.get(id) ?? 0) + 1
    seen.set(id, n)
    return n === 1 ? camel(id) : `${camel(id)}${n}`
  })
}

/** Regenerates content/meta.ts from the pages' content files. */
export function writeMetaIndex(root: string, pages: readonly { route: string; name: string }[]) {
  const present = pages.filter((p) => existsSync(join(root, contentFile(p.name))))
  const lines = [
    '// GENERATED by `dss g page`: page metadata by route, used by llms.txt. Do not edit by hand.',
    ...present.map((p) => `import { ${contentVar(p.name)} } from './${p.name}'`),
    '',
    'export const pageMeta: Record<string, { title: string; description: string }> = {',
    ...present.map((p) => `  '${p.route}': ${contentVar(p.name)}.meta,`),
    '}',
    '',
  ]
  writeFile(join(root, 'content/meta.ts'), lines.join('\n'))
}

/** Sets the nav label for a route inside content/site.ts (`nav: { ... }`). */
export function setNavLabel(root: string, route: string, label: string) {
  const file = join(root, 'content/site.ts')
  const text = readFileSync(file, 'utf8')
  const match = /nav: \{([^}]*)\}/.exec(text)
  if (!match) return
  const entries = new Map<string, string>()
  for (const m of (match[1] ?? '').matchAll(/'([^']+)':\s*'((?:[^'\\]|\\.)*)'/g))
    entries.set(m[1] as string, m[2] as string)
  if (!entries.has(route)) entries.set(route, label.replace(/'/g, "\\'"))
  const body = [...entries].map(([r, l]) => `'${r}': '${l}'`).join(', ')
  writeFile(file, text.replace(match[0], `nav: { ${body} }`))
}

/** Appends a section to an existing page and its content file. Returns false when the files were reshaped by hand. */
export function appendSection(
  root: string,
  route: string,
  name: string,
  section: PageSection,
  value: unknown,
): boolean {
  const pagePath = join(root, pageFile(route))
  const contentPath = join(root, contentFile(name))
  if (!existsSync(pagePath) || !existsSync(contentPath)) return false
  const page = readFileSync(pagePath, 'utf8')
  const content = readFileSync(contentPath, 'utf8')
  const v = contentVar(name)
  if (!page.includes('    </main>') || !content.includes('} as const')) return false
  let nextPage = page.replace(
    '    </main>',
    `      <${section.component} {...${v}.${section.key}} />\n    </main>`,
  )
  const importLine = `import { ${section.component} } from '${section.importPath}'`
  if (!nextPage.includes(importLine))
    nextPage = nextPage.replace(/(import manifest from '@\/site\.manifest'\n)/, `${importLine}\n$1`)
  let nextContent = content.replace(
    /\} as const\s*$/,
    `  ${section.key}: ${contentTs(value)},\n} as const\n`,
  )
  if (
    nextContent.includes(' as Route') &&
    !nextContent.includes("import type { Route } from 'next'")
  ) {
    nextContent = `import type { Route } from 'next'\n\n${nextContent}`
  }
  writeFile(pagePath, nextPage)
  writeFile(contentPath, nextContent)
  return true
}
