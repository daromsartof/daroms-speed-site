const GENERATED = '<!-- GENERATED by `dss catalog`: do not edit by hand. -->'

type Entry = { name: string; props: string }

/** @catalog / @props pairs from JSDoc blocks. */
export function parseCatalog(source: string): Entry[] {
  const out: Entry[] = []
  for (const block of source.matchAll(/\/\*\*([\s\S]*?)\*\//g)) {
    const text = (block[1] ?? '').replace(/^\s*\*\s?/gm, '').replace(/\s+/g, ' ')
    const name = /@catalog\s+(.*?)(?=@(?:props|example)\b|$)/.exec(text)?.[1]?.trim()
    if (!name) continue
    out.push({
      name,
      props: /@props\s+(.*?)(?=@(?:catalog|example)\b|$)/.exec(text)?.[1]?.trim() ?? '',
    })
  }
  return out
}

/** Exported value names of an entry file (re-exports and declarations, types excluded). */
export function exportedNames(file: string): string[] {
  const source = readFileSync(file, 'utf8')
  const names: string[] = []
  for (const m of source.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of (m[1] ?? '').split(',')) {
      const name = part.trim()
      if (name && !name.startsWith('type ')) names.push(name.split(/\s+as\s+/).pop() as string)
    }
  }
  for (const m of source.matchAll(/export\s+(?:async\s+)?(?:function|const)\s+(\w+)/g))
    names.push(m[1] as string)
  for (const m of source.matchAll(/export\s+\*\s+from\s+'(\.\/[^']+)'/g)) {
    names.push(...exportedNames(join(file, '..', m[1] as string)))
  }
  return [...new Set(names)]
}

