/** core/CATALOG.md: everything an agent needs instead of reading core sources. */
export function buildCatalog(core: string): string {
  const uiDir = join(core, 'packages/ui/src')
  const ui = readdirSync(uiDir)
    .filter((f) => f.endsWith('.tsx'))
    .sort()
    .flatMap((f) =>
      parseCatalog(readFileSync(join(uiDir, f), 'utf8')).map((e) => ({ ...e, file: f })),
    )
  const motionDir = join(core, 'packages/motion/src')
  const motion = [
    ...readdirSync(motionDir)
      .filter((f) => f.endsWith('.tsx'))
      .sort()
      .flatMap((f) => parseCatalog(readFileSync(join(motionDir, f), 'utf8'))),
    ...parseCatalog(readFileSync(join(core, 'packages/three/src/scene.tsx'), 'utf8')),
  ]
  const sections = listSections().sort((a, b) =>
    `${a.id}/${a.variant}`.localeCompare(`${b.id}/${b.variant}`),
  )
  const api = (pkg: string, entry: string) => {
    const file = join(core, 'packages', pkg, entry)
    return existsSync(file) ? exportedNames(file).join(', ') : ''
  }
  return [
    GENERATED,
    '# dss catalog',
    '',
    'Read this file, never the core sources. Site sections: `grep -h @catalog components/sections/*.tsx`.',
    '',
    TOKENS,
    "## @dss/ui (`import { Heading } from '@dss/ui'`; client: `@dss/ui/accordion`)",
    '',
    '| Component | Props |',
    '|---|---|',
    ...ui.map((e) => `| ${cell(e.name)} | ${cell(e.props)} |`),
    '',
    '## Motion and 3D (`@dss/motion`, client `@dss/motion/count-up`; `@dss/three` only in components/3d)',
    '',
    '| Component | Props |',
    '|---|---|',
    ...motion.map((e) => `| ${cell(e.name)} | ${cell(e.props)} |`),
    '',
    'Scenes (`pnpm dss add scene <id>`, copied into components/3d/, poster fallback, skipped when DNA three is none):',
    '',
    ...listScenes().map((s) => `- \`${s.id}\` (${s.component}): ${s.description}`),
    '',
    '## Registry sections (`pnpm dss add section <id>/<variant> --page /route`)',
    '',
    'Without a variant, a variant that fits the DNA archetype is picked with the site seed (one variant per id per site). Props mirror `example.json`.',
    '',
    '| Section | Component | Use | Fits |',
    '|---|---|---|---|',
    ...sections.map(
      (s) =>
        `| ${s.id}/${s.variant} | ${s.component} | ${cell(s.description)} | ${s.fits.join(', ')} |`,
    ),
    '',
    '## Archetypes (design.dna.ts `archetype`)',
    '',
    ...ARCHETYPE_LIST.map(
      (a) => `- **${a.id}**: ${a.read}. Signature: ${a.signature}. Avoid: ${a.avoid}.`,
    ),
    '',
    '## Font pairings (design.dna.ts `fonts`)',
    '',
    ...FONT_PAIRS.map(
      (p) =>
        `- \`${p.id}\`: ${p.display.family} / ${p.body.family}${p.mono ? ` + ${p.mono.family}` : ''}, ${p.note} (${p.fits.join(', ')})`,
    ),
    '',
    '## Package APIs',
    '',
    `- \`@dss/seo\`: ${api('seo', 'src/index.ts')}. \`@dss/seo/react\`: JsonLd.`,
    `- \`@dss/security/server\`: ${api('security', 'src/server.ts')}.`,
    `- \`@dss/site/config\` (next.config.ts, manifest): ${api('site', 'src/config.ts')}.`,
    `- CSP presets (manifest \`security.csp.presets\`): ${Object.keys(CSP_PRESETS).join(', ')}.`,
    `- \`@dss/data\`: ${api('data', 'src/index.ts')}; \`/d1\`: d1Db; \`/libsql\`: libsqlDb; \`/config\`: dssDrizzleConfig.`,
    '',
  ].join('\n')
}

function ruleSummary(text: string): string {
  const body = text.replace(/^---\n[\s\S]*?\n---\n/, '')
  const quote = /^> (.+)$/m.exec(body)?.[1]
  return quote ?? /^# (.+)$/m.exec(body)?.[1] ?? ''
}

/** _ai/digest.md: one line per rule, so Claude knows every rule exists without loading the bodies. */
export function buildDigest(ai: string): string {
  const lines = [
    GENERATED,
    '# dss rules digest (one line per rule)',
    '',
    'Detailed rules load automatically for the files you touch (`.claude/rules/`).',
    'On-demand rules: read `.claude/rules-ondemand/<name>.md` when the topic comes up.',
    '',
  ]
  for (const [folder, label] of [
    ['rules', ''],
    ['rules-ondemand', ' (on demand)'],
  ] as const) {
    const dir = join(ai, folder)
    for (const file of readdirSync(dir)
      .filter((f) => f.startsWith('dss-') && f.endsWith('.md'))
      .sort()) {
      lines.push(
        `- **${file.replace(/\.md$/, '')}**${label}: ${ruleSummary(readFileSync(join(dir, file), 'utf8'))}`,
      )
    }
  }
  return `${lines.join('\n')}\n`
}
